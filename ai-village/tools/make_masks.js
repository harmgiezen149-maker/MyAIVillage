// Builds the first-pass walk and cover layers from the hand-placed shapes in game/world.js
// and writes them to game/masks.js. Run: node tools/make_masks.js
//
// Each place gets two grids of 4 × 4 unit cells:
//   walk:  1 = the character may stand here, 0 = blocked
//   cover: 0 = nothing, 1 = always drawn over the character ("under"),
//          2 = drawn over the character only when his feet are above its bottom edge ("behind")
// Harm corrects these in the village's paint mode (key E); saved corrections are folded back in here.

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..');
const world = {};
vm.runInNewContext(fs.readFileSync(path.join(root, 'game/world.js'), 'utf8') + '\nthis.out = { MAP, WALK_AREA, MAP_OBSTACLES, BUILDINGS, ROOMS };', world);
const { MAP, WALK_AREA, MAP_OBSTACLES, BUILDINGS, ROOMS } = world.out;

const CELL = 4;

// Tree tops that hang over walkable ground: walkable, and covering.
const CANOPIES = [
  { ellipse: [715, 1605, 118, 98], trunk: [672, 1700, 76, 76] },   // big tree south of the family cottage
  { ellipse: [870, 935, 95, 80], trunk: [792, 1010, 44, 75] },     // swing tree west of the square
];

function insidePolygon(x, y, poly) {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
function inShape(x, y, s) {
  if (s.box) s = s.box;
  if (s.ellipse) {
    const [cx, cy, rx, ry] = s.ellipse;
    return ((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2 < 1;
  }
  return x >= s[0] && x < s[0] + s[2] && y >= s[1] && y < s[1] + s[3];
}
function footOf(box, share) {
  const h = Math.round(box[3] * share);
  return [box[0], box[1] + box[3] - h, box[2], h];
}

function makeGrid(w, h) {
  const cols = Math.ceil(w / CELL), rows = Math.ceil(h / CELL);
  return { cols, rows, walk: new Uint8Array(cols * rows), cover: new Uint8Array(cols * rows) };
}
function eachCell(g, fn) {
  for (let r = 0; r < g.rows; r++) for (let c = 0; c < g.cols; c++) fn(r * g.cols + c, c * CELL + CELL / 2, r * CELL + CELL / 2);
}

function encode(arr) {
  let out = '', i = 0;
  while (i < arr.length) {
    let j = i;
    while (j < arr.length && arr[j] === arr[i]) j++;
    out += String.fromCharCode(65 + arr[i]) + (j - i).toString(36);
    i = j;
  }
  return out;
}

// ---------- town ----------
function town() {
  const g = makeGrid(MAP.w, MAP.h);
  const blocks = [], covers = [];
  for (const o of MAP_OBSTACLES) {
    blocks.push(o.small ? footOf(o.box, 0.45) : o);   // small things: only the foot blocks
    covers.push(o);
  }
  eachCell(g, (i, x, y) => {
    let walk = insidePolygon(x, y, WALK_AREA) || CANOPIES.some((t) => inShape(x, y, t));
    if (blocks.some((b) => inShape(x, y, b)) || CANOPIES.some((t) => inShape(x, y, t.trunk))) walk = false;
    g.walk[i] = walk ? 1 : 0;
    const covered = !walk || covers.some((b) => inShape(x, y, b)) || CANOPIES.some((t) => inShape(x, y, t) || inShape(x, y, t.trunk));
    g.cover[i] = covered ? 2 : 0;
  });
  // keep every doorway open and uncovered
  for (const b of BUILDINGS) clearAround(g, b.door[0], b.door[1], 14);
  return g;
}

function clearAround(g, x, y, radius) {
  eachCell(g, (i, cx, cy) => {
    if (Math.hypot(cx - x, cy - y) <= radius) { g.walk[i] = 1; g.cover[i] = 0; }
  });
}

// ---------- rooms ----------
function room(r) {
  const g = makeGrid(1200, 896);
  const [fx, fy, fw, fh] = r.floor;
  const [ex, ey] = r.exit;
  const feet = r.obstacles.map((o) => footOf(o, 0.5));
  eachCell(g, (i, x, y) => {
    const onFloor = x >= fx && x < fx + fw && y >= fy && y < fy + fh;
    const doorway = Math.abs(x - ex) < 50 && y >= fy && y <= ey + 40;
    let walk = (onFloor || doorway) && !feet.some((b) => inShape(x, y, b));
    g.walk[i] = walk ? 1 : 0;
    g.cover[i] = !walk || r.obstacles.some((b) => inShape(x, y, b)) ? 2 : 0;
    if (doorway) g.cover[i] = 0;
  });
  return g;
}

const out = { town: town() };
for (const id of Object.keys(ROOMS)) out[id] = room(ROOMS[id]);

let js = '// Generated by tools/make_masks.js — the walk and cover layers for every place.\n';
js += '// Letters are values (A = 0, B = 1, C = 2), each followed by how many cells in a row have it (base 36).\n';
js += 'const DEFAULT_MASKS = {\n';
for (const [id, g] of Object.entries(out)) {
  js += `  '${id}': { cell: ${CELL}, cols: ${g.cols}, rows: ${g.rows},\n    walk: '${encode(g.walk)}',\n    cover: '${encode(g.cover)}' },\n`;
}
js += '};\n';
fs.writeFileSync(path.join(root, 'game/masks.js'), js);
console.log('wrote game/masks.js', (js.length / 1024).toFixed(1) + ' KB');
