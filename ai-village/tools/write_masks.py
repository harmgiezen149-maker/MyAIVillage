"""Writes game/masks.js from the walk and cover grids made by tools/town_walk.py and tools/room_walk.py,
and the picture art/maps/walkable-areas.jpg for Harm to check.
Usage: python3 tools/town_walk.py && python3 tools/room_walk.py && python3 tools/write_masks.py"""
import os, datetime
import numpy as np
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'tools/out')
ROOMS = ['council-hall', 'post-house', 'counting-house', 'scholars-tower', 'artisans-workshop', 'family-cottage',
         'bards-house', 'criers-press', 'heralds-lodge', 'carriers-depot']

def encode(arr):
    arr = arr.ravel(); out = []; i = 0
    while i < len(arr):
        j = i
        while j < len(arr) and arr[j] == arr[i]: j += 1
        out.append(chr(65 + int(arr[i])) + np.base_repr(j - i, 36).lower()); i = j
    return ''.join(out)

def main():
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')
    places = [('town', 'town')] + [(r, r) for r in ROOMS]
    js = ['// Generated by tools/write_masks.py: where people can walk, worked out from the art (tools/town_walk.py, tools/room_walk.py).',
          '// Letters are values (A = 0, B = 1, C = 2), each followed by how many cells in a row have it (base 36).',
          f"// Paint-mode corrections saved before {stamp} were made on the old version and are not applied.",
          f"const MASKS_MADE = '{stamp}';", 'const DEFAULT_MASKS = {']
    for pid, f in places:
        walk = np.load(os.path.join(OUT, f'{f}-walk.npy')); cover = np.load(os.path.join(OUT, f'{f}-cover.npy'))
        rows, cols = walk.shape
        js.append(f"  '{pid}': {{ cell: 4, cols: {cols}, rows: {rows},\n    walk: '{encode(walk)}',\n    cover: '{encode(cover)}' }},")
    js.append('};\n')
    open(os.path.join(ROOT, 'game/masks.js'), 'w').write('\n'.join(js))
    print('wrote game/masks.js')

    # the picture: town large, rooms below. green = walk, yellow = walk but hidden behind a roof or tree, red = no
    def tint(img, walk, cover, size):
        col = np.zeros(walk.shape + (3,), np.uint8); col[:] = [225, 45, 45]
        col[walk == 1] = [40, 215, 80]; col[(walk == 1) & (cover > 0)] = [250, 210, 40]
        return Image.blend(img.convert('RGB').resize(size), Image.fromarray(col).resize(size, Image.NEAREST), 0.42)
    town = tint(Image.open(os.path.join(ROOT, 'assets/map.jpg')), np.load(f'{OUT}/town-walk.npy'), np.load(f'{OUT}/town-cover.npy'), (1600, 1195))
    tiles = []
    for r in ROOMS:
        t = tint(Image.open(os.path.join(ROOT, f'assets/rooms/{r}.jpg')), np.load(f'{OUT}/{r}-walk.npy'), np.zeros((224, 300)), (320, 239))
        ImageDraw.Draw(t).rectangle([0, 0, 320, 18], fill=(30, 22, 15)); ImageDraw.Draw(t).text((6, 3), r.replace('-', ' ').title(), fill=(242, 193, 78))
        tiles.append(t)
    sheet = Image.new('RGB', (1600, 1195 + 2 * 239 + 60), (30, 22, 15))
    sheet.paste(town, (0, 0))
    d = ImageDraw.Draw(sheet)
    y = 1195 + 8
    for sw, label in (((40, 215, 80), 'can walk'), ((250, 210, 40), 'can walk, hidden behind a roof or tree top'), ((225, 45, 45), "can't walk")):
        pass
    x = 10
    for sw, label in (((40, 215, 80), 'green: can walk'), ((250, 210, 40), 'yellow: can walk, hidden behind a roof or tree top'), ((225, 45, 45), "red: can't walk")):
        d.rectangle([x, y, x + 18, y + 18], fill=sw); d.text((x + 26, y + 4), label, fill=(240, 230, 210)); x += 360
    for k, t in enumerate(tiles):
        sheet.paste(t, ((k % 5) * 320, 1195 + 40 + (k // 5) * 239))
    os.makedirs(os.path.join(ROOT, 'art/maps'), exist_ok=True)
    sheet.save(os.path.join(ROOT, 'art/maps/walkable-areas.jpg'), quality=86)
    print('wrote art/maps/walkable-areas.jpg')

if __name__ == '__main__':
    main()
